import type { Metadata } from 'next';
import { Inter, JetBrains_Mono } from 'next/font/google';
import { notFound } from 'next/navigation';
import { NextIntlClientProvider, hasLocale } from 'next-intl';
import { getTranslations, setRequestLocale } from 'next-intl/server';

import '../globals.css';

import { Footer } from '@/components/Footer';
import { Header } from '@/components/Header';
import { ScrollReveal } from '@/components/ScrollReveal';
import { htmlLang, routing } from '@/i18n/routing';
import { asset, siteUrl } from '@/lib/site';

const sans = Inter({
  subsets: ['latin'],
  display: 'swap',
  variable: '--font-sans-var',
});

const mono = JetBrains_Mono({
  subsets: ['latin'],
  display: 'swap',
  variable: '--font-mono-var',
});

type LayoutProps = {
  children: React.ReactNode;
  params: Promise<{ locale: string }>;
};

export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }));
}

export async function generateMetadata({
  params,
}: Omit<LayoutProps, 'children'>): Promise<Metadata> {
  const { locale } = await params;
  if (!hasLocale(routing.locales, locale)) return {};

  const t = await getTranslations({ locale, namespace: 'meta' });

  // Derived from `routing.locales`, so adding a language needs no edit here.
  const languages = Object.fromEntries(
    routing.locales.map((candidate) => [htmlLang[candidate], `/${candidate}/`]),
  );

  return {
    metadataBase: new URL(siteUrl),
    title: t('title'),
    description: t('description'),
    alternates: {
      canonical: `/${locale}/`,
      languages,
    },
    openGraph: {
      type: 'website',
      locale: htmlLang[locale],
      url: `/${locale}/`,
      title: t('title'),
      description: t('description'),
      images: [
        {
          // Generated by `app/[locale]/og.png/route.tsx`. Referenced by hand so
          // the exported file keeps its `.png` extension — see that file.
          url: asset(`/${locale}/og.png`),
          width: 1200,
          height: 630,
          alt: t('title'),
        },
      ],
    },
    twitter: { card: 'summary_large_image' },
  };
}

export default async function LocaleLayout({ children, params }: LayoutProps) {
  const { locale } = await params;
  if (!hasLocale(routing.locales, locale)) notFound();

  // Required for static rendering: tells next-intl which locale to use in
  // server components below this point without reading the request.
  setRequestLocale(locale);

  const t = await getTranslations('nav');

  return (
    <html lang={htmlLang[locale]} className={`${sans.variable} ${mono.variable}`}>
      <body className="min-h-dvh antialiased">
        {/* Needed by next-intl's locale-aware `Link`, and by any client
            component that reads translations later on. */}
        <NextIntlClientProvider>
          <a
            href="#main"
            className="focus:bg-ink focus:text-paper sr-only focus:not-sr-only focus:fixed focus:top-4 focus:left-4 focus:z-50 focus:rounded-full focus:px-4 focus:py-2 focus:font-mono focus:text-xs"
          >
            {t('skipToContent')}
          </a>
          <Header locale={locale} />
          <main id="main">{children}</main>
          <Footer />
          <ScrollReveal />
        </NextIntlClientProvider>
      </body>
    </html>
  );
}
